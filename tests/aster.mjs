import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { join } from 'node:path'
import { poll, delay } from './browser-helper.mjs'

export async function testAster({ send, evaluate, screenshot, downloads }) {
  const click = selector => evaluate(`document.querySelector(${JSON.stringify(selector)}).click()`)
  const set = (selector, value) => evaluate(`(() => { const el = document.querySelector(${JSON.stringify(selector)}); el.value = ${JSON.stringify(value)}; el.dispatchEvent(new Event('input', { bubbles: true })); el.dispatchEvent(new Event('change', { bubbles: true })); })()`)
  await send('Page.navigate', { url: 'http://127.0.0.1:4187/dich-vu/thiet-ke-website/#mau-giao-dien' })
  await poll(() => evaluate(`document.readyState === 'complete' && document.querySelector('.car-preview')`))
  assert.equal(await evaluate(`document.querySelectorAll('.work-card').length`), 3)
  const demoUrl = await evaluate(`document.querySelector('.car-preview').href`)
  assert.equal(demoUrl, 'http://127.0.0.1:4187/demos/aster/')
  assert.deepEqual(await evaluate(`[...document.querySelectorAll('.work-actions a[target="_blank"]')].map(a => a.pathname)`), ['/demos/aster/', '/demos/an-studio/', '/demos/orbit/'])
  await click('[data-concept="Aster S5 — Landing page ô tô"]')
  await poll(() => evaluate(`document.querySelector('#plan')?.value === 'launch'`))
  assert.equal(await evaluate(`document.querySelector('#plan').value`), 'launch')
  assert.match(await evaluate(`document.querySelector('#message').value`), /Aster S5/)
  await send('Page.navigate', { url: demoUrl })
  await poll(() => evaluate(`document.readyState === 'complete' && document.querySelector('.color-picker')?.hidden === false`))
  await evaluate(`document.fonts.ready`)
  assert.equal(await evaluate(`document.querySelectorAll('h1').length`), 1)
  assert.deepEqual(await evaluate(`[...document.querySelectorAll('a[href^="#"]')].map(a=>a.getAttribute('href')).filter(h=>h.length>1 && !document.getElementById(h.slice(1)))`), [])
  for (const width of [1440, 1024, 768, 600, 390, 320]) {
    await send('Emulation.setDeviceMetricsOverride', { width, height: 900, deviceScaleFactor: 1, mobile: width < 761 })
    assert.equal(await evaluate(`document.documentElement.scrollWidth <= ${width}`), true, `Aster overflow at ${width}px`)
  }
  await click('#menu-toggle')
  assert.equal(await evaluate(`document.querySelector('#menu-toggle').getAttribute('aria-expanded')`), 'true')
  await click('#navigation a[href="#thong-so"]')
  assert.equal(await evaluate(`document.querySelector('#menu-toggle').getAttribute('aria-expanded')`), 'false')
  await click('[data-version="premium"]')
  assert.equal(await evaluate(`document.querySelector('#selected-price').textContent`), '749.000.000₫')
  assert.equal(await evaluate(`document.querySelector('[name="version"]').value`), 'premium')
  await click('[data-color="graphite"]')
  await evaluate(`document.querySelector('#car-image').decode()`)
  assert.match(await evaluate(`document.querySelector('#car-image').src`), /aster-graphite.png$/)
  assert.equal(await evaluate(`document.querySelector('[name="color"]').value`), 'graphite')
  await click('.hero-bottom [data-purpose="Lái thử"]')
  assert.equal(await evaluate(`document.querySelector('[name="purpose"]').value`), 'Lái thử')
  await set('[name="name"]', '<img src=x onerror=alert(1)>')
  await set('[name="phone"]', '123')
  await click('#car-form [type="submit"]')
  assert.equal(await evaluate(`document.querySelector('#request-dialog').open`), false)
  await set('[name="phone"]', '090 123 4567')
  await click('#car-form [type="submit"]')
  assert.equal(await evaluate(`document.querySelector('#request-dialog').open`), true)
  const request = await evaluate(`document.querySelector('#request-summary').value`)
  assert.match(request, /S5 Premium/)
  assert.match(request, /Xám graphite/)
  assert.match(request, /749.000.000₫/)
  assert.match(request, /Nhu cầu: Lái thử/)
  assert.match(request, /chưa được gửi/)
  assert.equal(await evaluate(`document.querySelectorAll('#request-dialog img').length`), 0)
  await evaluate(`Object.defineProperty(navigator, 'clipboard', { configurable:true, value:{ writeText: async text => { window.asterCopied = text } } })`)
  await click('#copy-request')
  await poll(() => evaluate(`document.querySelector('#request-status').textContent.includes('Đã sao chép')`))
  assert.equal(await evaluate(`window.asterCopied`), request)
  await evaluate(`Object.defineProperty(navigator, 'clipboard', { configurable:true, value:{ writeText: async () => { throw new Error('Denied') } } })`)
  await click('#copy-request')
  await poll(() => evaluate(`document.activeElement.id === 'request-summary'`))
  await click('#download-request')
  await poll(async () => (await readFile(join(downloads, 'yeu-cau-aster-s5.txt'), 'utf8')).includes('S5 Premium'))
  await send('Input.dispatchKeyEvent', { type: 'keyDown', key: 'Escape', code: 'Escape', windowsVirtualKeyCode: 27 })
  await send('Input.dispatchKeyEvent', { type: 'keyUp', key: 'Escape', code: 'Escape', windowsVirtualKeyCode: 27 })
  await poll(() => evaluate(`!document.querySelector('#request-dialog').open`))
  await set('[name="version"]', 'standard')
  await set('[name="color"]', 'white')
  assert.equal(await evaluate(`document.querySelector('#selected-price').textContent`), '649.000.000₫')
  assert.equal(await evaluate(`document.querySelector('[data-version="standard"]').getAttribute('aria-pressed')`), 'true')
  await evaluate(`Promise.all([...document.images].map(img => img.decode()))`)
  await send('Emulation.setDeviceMetricsOverride', { width: 1440, height: 1050, deviceScaleFactor: 1, mobile: false })
  await evaluate(`document.documentElement.style.scrollBehavior = 'auto'; window.scrollTo(0, 0)`)
  await screenshot('/tmp/aster-desktop.png', true)
  await screenshot('/tmp/aster-desktop-hero.png')
  await send('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true })
  await screenshot('/tmp/aster-mobile.png', true)
  await screenshot('/tmp/aster-mobile-hero.png')
  await click('.demo-bar a:last-child')
  await poll(() => evaluate(`document.querySelector('#message')?.value.includes('Aster S5')`))
  assert.equal(await evaluate(`document.querySelector('#plan').value`), 'launch')
  assert.equal(await evaluate(`location.hash`), '#lien-he')
  await send('Emulation.setScriptExecutionDisabled', { value: true })
  await send('Page.navigate', { url: demoUrl })
  await delay(500)
  await send('Emulation.setScriptExecutionDisabled', { value: false })
  assert.match(await evaluate(`document.querySelector('table').textContent`), /749 triệu/)
  assert.equal(await evaluate(`document.querySelector('#car-form [type="submit"]').disabled`), true)
  assert.equal(await evaluate(`getComputedStyle(document.querySelector('#navigation')).display !== 'none'`), true)
  console.log('PASS: Aster at 6 widths, version/color synchronization, quote/test drive, validation, clipboard/TXT, sample selection with Launch plan, local images and no-JavaScript content.')
}
