import assert from 'node:assert/strict'
import { poll, delay } from './browser-helper.mjs'

export async function testOrbitApp({ send, evaluate, screenshot }) {
  const click = selector => evaluate(`document.querySelector(${JSON.stringify(selector)}).click()`)
  const set = (selector, value) => evaluate(`(() => { const el = document.querySelector(${JSON.stringify(selector)}); el.value = ${JSON.stringify(value)}; el.dispatchEvent(new Event('input', { bubbles: true })); el.dispatchEvent(new Event('change', { bubbles: true })); })()`)
  // Open the application directly from the Orbit showcase on CoreBrisk.
  const appUrl = await evaluate(`document.querySelector('.saas-preview').href`)
  assert.equal(appUrl, 'http://127.0.0.1:4187/demos/orbit/')
  assert.equal(await evaluate(`document.querySelector('.saas-preview').closest('.work-card').querySelector('.work-actions a').href`), appUrl)
  await send('Page.navigate', { url: appUrl })
  await poll(() => evaluate(`document.readyState === 'complete' && document.querySelector('.metrics')`))
  await evaluate('document.fonts.ready')
  assert.equal(await evaluate(`document.querySelectorAll('h1').length`), 1)
  assert.equal(await evaluate(`document.querySelector('.demo-banner a:last-child').getAttribute('href')`), '/?concept=orbit#lien-he')
  assert.equal(await evaluate(`document.querySelector('.sidebar-help a').getAttribute('href')`), '/#giao-dien')
  for (const width of [1440, 1024, 768, 600, 390, 320]) {
    await send('Emulation.setDeviceMetricsOverride', { width, height: 950, deviceScaleFactor: 1, mobile: width < 901 })
    for (const view of ['overview', 'tasks', 'projects', 'team']) {
      await click(`[data-view="${view}"]`)
      await poll(() => evaluate(`document.querySelector('[data-view="${view}"]').getAttribute('aria-current') === 'page'`))
      assert.equal(await evaluate(`document.documentElement.scrollWidth <= ${width}`), true, `Orbit app ${view} overflow at ${width}px`)
    }
  }
  await click('#sidebar-toggle')
  assert.equal(await evaluate(`document.querySelector('#sidebar-toggle').getAttribute('aria-expanded')`), 'true')
  await click('[data-view="tasks"]')
  await poll(() => evaluate(`document.querySelector('#task-search')`))
  assert.equal(await evaluate(`document.querySelector('#sidebar-toggle').getAttribute('aria-expanded')`), 'false')
  assert.equal(await evaluate(`document.querySelectorAll('.task-card').length`), 9)
  await set('#task-search', 'Không tìm thấy 999')
  assert.equal(await evaluate(`document.querySelectorAll('.task-card').length`), 0)
  assert.match(await evaluate(`document.querySelector('#result-count').textContent`), /^0 \/ 9/)
  await set('#task-search', '')
  await set('#project-filter', 'website')
  assert.equal(await evaluate(`document.querySelectorAll('.task-card').length`), 3)
  await set('#owner-filter', 'ma')
  assert.equal(await evaluate(`document.querySelectorAll('.task-card').length`), 1)
  await click('[data-layout="list"]')
  assert.equal(await evaluate(`document.querySelectorAll('.list-row').length`), 1)
  await click('#new-task')
  await set('[name="title"]', '     ')
  await click('#task-form button[type="submit"]')
  assert.equal(await evaluate(`document.querySelector('#task-dialog').open`), true)
  await set('[name="title"]', 'Test <img src=x onerror=alert(1)>')
  await set('[name="description"]', 'Nội dung kiểm tra tạo và sửa công việc.')
  await set('[name="status"]', 'doing')
  await click('#task-form button[type="submit"]')
  await poll(() => evaluate(`!document.querySelector('#task-dialog').open`))
  assert.equal(await evaluate(`document.querySelector('#nav-task-count').textContent`), '10')
  assert.equal(await evaluate(`document.querySelectorAll('#task-results img').length`), 0)
  assert.match(await evaluate(`document.querySelector('#task-results').textContent`), /Test <img/)
  assert.equal(await evaluate(`document.querySelectorAll('.list-row').length`), 2)
  await evaluate(`document.querySelector('[data-edit="10"]').focus()`)
  await click('[data-edit="10"]')
  await send('Input.dispatchKeyEvent', { type: 'keyDown', key: 'Escape', code: 'Escape', windowsVirtualKeyCode: 27 })
  await send('Input.dispatchKeyEvent', { type: 'keyUp', key: 'Escape', code: 'Escape', windowsVirtualKeyCode: 27 })
  await poll(() => evaluate(`!document.querySelector('#task-dialog').open && document.activeElement.dataset.edit === '10'`))
  await click('[data-edit="10"]')
  await set('[name="status"]', 'done')
  await set('[name="owner"]', 'lt')
  await click('#task-form button[type="submit"]')
  await poll(() => evaluate(`!document.querySelector('#task-dialog').open`))
  assert.equal(await evaluate(`document.querySelectorAll('.list-row').length`), 1, 'Updated owner should move task out of member filter')
  await click('[data-view="projects"]')
  await poll(() => evaluate(`document.querySelector('.projects-grid')`))
  assert.match(await evaluate(`document.querySelector('.project-card').textContent`), /2\/4 hoàn thành/)
  await click('.project-card [data-project-link]')
  await poll(() => evaluate(`document.querySelector('#project-filter')?.value === 'website'`))
  assert.equal(await evaluate(`document.querySelectorAll('.list-row').length`), 4)
  await click('[data-view="team"]')
  await poll(() => evaluate(`document.querySelector('.team-grid')`))
  await click('[data-owner-link="lt"]')
  await poll(() => evaluate(`document.querySelector('#owner-filter')?.value === 'lt'`))
  assert.equal(await evaluate(`document.querySelectorAll('.list-row').length`), 3)
  await click('[data-view="overview"]')
  await poll(() => evaluate(`document.querySelector('.metrics')`))
  assert.match(await evaluate(`document.querySelector('.metric.highlight strong').textContent`), /4.*10/)
  await click('[data-complete]')
  assert.match(await evaluate(`document.querySelector('.metric.highlight strong').textContent`), /5.*10/)
  // Reload returns to the initial sample state, then capture the unmodified UI.
  await send('Page.reload')
  await poll(() => evaluate(`document.querySelector('#nav-task-count')?.textContent === '9' && document.querySelector('.metrics')`))
  await send('Emulation.setDeviceMetricsOverride', { width: 1440, height: 1050, deviceScaleFactor: 1, mobile: false })
  await screenshot('/tmp/orbit-app-overview.png', true)
  await click('[data-view="tasks"]')
  await poll(() => evaluate(`document.querySelector('.board')`))
  await screenshot('/tmp/orbit-app-board.png', true)
  await click('[data-edit="1"]')
  await screenshot('/tmp/orbit-app-dialog.png')
  await click('#cancel-dialog')
  await send('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true })
  await screenshot('/tmp/orbit-app-mobile.png', true)
  await click('.demo-banner a:last-child')
  await poll(() => evaluate(`document.querySelector('#message')?.value.includes('Orbit — Công nghệ & SaaS')`))
  await send('Emulation.setScriptExecutionDisabled', { value: true })
  await send('Page.navigate', { url: appUrl })
  await delay(500)
  await send('Emulation.setScriptExecutionDisabled', { value: false })
  assert.match(await evaluate(`document.querySelector('noscript').textContent`), /Bật JavaScript/)
  assert.equal(await evaluate(`document.querySelector('.demo-banner a').getAttribute('href')`), '/#giao-dien')
  console.log('PASS: Orbit application at 6 widths, navigation, search and combined filters, board/list, task creation/editing, escaped input, derived progress, member assignments, keyboard dialog, reset on reload and consultation return.')
}
