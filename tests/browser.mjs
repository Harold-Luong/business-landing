const downloads = await mkdtemp(join(tmpdir(), 'corebrisk-downloads-'))
let serverError = ''
server.stderr.on('data', (chunk) => { serverError += chunk })
try {
  await poll(async () => (await fetch('http://127.0.0.1:4187')).ok)
  await withBrowser(async ({ send, evaluate, screenshot, errors }) => {
    const click = (selector) => evaluate(`document.querySelector(${JSON.stringify(selector)}).click()`)
    const set = (selector, value) => evaluate(`(() => { const el = document.querySelector(${JSON.stringify(selector)}); el.value = ${JSON.stringify(value)}; el.dispatchEvent(new Event('input', { bubbles: true })); })()`)
    await send('Emulation.setDeviceMetricsOverride', { width: 1440, height: 1050, deviceScaleFactor: 1, mobile: false })
    await send('Page.navigate', { url: 'http://127.0.0.1:4187' })
    await poll(() => evaluate(`document.querySelector('#year') && document.readyState === 'complete'`))
    await evaluate('document.fonts.ready')
    await testNavigation({ send, evaluate, screenshot })
    await testCtas({ send, evaluate, screenshot })
    await testPricing({ send, evaluate, screenshot })
    assert.equal(await evaluate(`document.querySelectorAll('h1').length`), 1)
    assert.equal(await evaluate(`document.fonts.check('400 16px "Be Vietnam Pro"')`), true)
    assert.deepEqual(await evaluate(`[...document.querySelectorAll('a[href^="#"]')].map(a=>a.getAttribute('href')).filter(h=>h.length>1 && !document.getElementById(h.slice(1)))`), [])
    await screenshot('/tmp/corebrisk-desktop.png', true)
    await screenshot('/tmp/corebrisk-desktop-hero.png')
    for (const width of [1440, 1024, 768, 600, 390, 320]) {
      await send('Emulation.setDeviceMetricsOverride', { width, height: 844, deviceScaleFactor: 1, mobile: width < 601 })
      assert.equal(await evaluate(`document.documentElement.scrollWidth <= ${width}`), true, `Horizontal overflow at ${width}px`)
      assert.equal(await evaluate(`document.querySelector('.hero-copy').getBoundingClientRect().right <= ${width}`), true, `Hero copy clipped at ${width}px`)
      assert.equal(await evaluate(`document.querySelector('.hero-visual').getBoundingClientRect().right <= ${width}`), true, `Hero mockup clipped at ${width}px`)
    }
    await send('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true })
    await evaluate(`document.documentElement.style.scrollBehavior = 'auto'; window.scrollTo(0,0)`)
    await screenshot('/tmp/corebrisk-mobile.png', true)
    await screenshot('/tmp/corebrisk-mobile-hero.png')
    await click('.menu-toggle')
    assert.equal(await evaluate(`document.querySelector('.menu-toggle').getAttribute('aria-expanded')`), 'true')
    await click('#navigation a[href="#bang-gia"]')
    assert.equal(await evaluate(`document.querySelector('.menu-toggle').getAttribute('aria-expanded')`), 'false')
    await click('.menu-toggle')
    await send('Input.dispatchKeyEvent', { type: 'keyDown', key: 'Escape', code: 'Escape', windowsVirtualKeyCode: 27 })
    await send('Input.dispatchKeyEvent', { type: 'keyUp', key: 'Escape', code: 'Escape', windowsVirtualKeyCode: 27 })
    assert.equal(await evaluate(`document.activeElement.className`), 'menu-toggle')
    assert.equal(await evaluate(`document.querySelector('.menu-toggle').getAttribute('aria-expanded')`), 'false')
    await click('.price-card.featured [data-select-plan]')
    assert.equal(await evaluate(`document.querySelector('#plan').options.length`), 9)
    assert.equal(await evaluate(`document.querySelector('#budget').options.length`), 5)
    assert.equal(await evaluate(`document.querySelector('#plan').value`), 'business')
    await click('[data-concept="An Studio — Kiến trúc & nội thất"]')
    assert.match(await evaluate(`document.querySelector('#message').value`), /An Studio/)
    await set('#name', 'Nguyễn Minh Anh')
    await set('#email', 'invalid-email')
    await click('#quote-form button[type="submit"]')
    assert.equal(await evaluate(`document.querySelector('#quote-dialog').open`), false)
    await set('#email', 'anh@example.test')
    await set('#message', '               ')
    await click('#quote-form button[type="submit"]')
    assert.equal(await evaluate(`document.querySelector('#quote-dialog').open`), false)
    await set('#message', 'Cần website doanh nghiệp với trang dịch vụ và blog.')
    await set('#company', '<img src=x onerror=alert(1)>')
    await click('#quote-form button[type="submit"]')
    assert.equal(await evaluate(`document.querySelector('#quote-dialog').open`), true)
    assert.match(await evaluate(`document.querySelector('#quote-summary').value`), /Business · từ 14,9 triệu/)
    assert.equal(await evaluate(`document.querySelector('#quote-dialog img')`), null)
    assert.equal(await evaluate(`document.querySelector('#email-quote').hidden`), true)
    await evaluate(`Object.defineProperty(navigator, 'clipboard', { configurable:true, value: { writeText: async (text) => { window.copiedText = text } } })`)
    await click('#copy-quote')
    await poll(() => evaluate(`document.querySelector('#copy-status').textContent.includes('Đã sao chép')`))
    assert.equal(await evaluate(`window.copiedText === document.querySelector('#quote-summary').value`), true)
    await evaluate(`Object.defineProperty(navigator, 'clipboard', { configurable:true, value: { writeText: async () => { throw new Error('Clipboard denied') } } })`)
    await click('#copy-quote')
    await poll(() => evaluate(`document.querySelector('#copy-status').textContent.includes('Ctrl+C')`))
    assert.equal(await evaluate(`document.activeElement.id`), 'quote-summary')
    await send('Browser.setDownloadBehavior', { behavior: 'allow', downloadPath: downloads })
    await click('#download-quote')
    await poll(async () => (await readdir(downloads)).includes('yeu-cau-tu-van-du-an.txt'))
    assert.match(await readFile(join(downloads, 'yeu-cau-tu-van-du-an.txt'), 'utf8'), /Nguyễn Minh Anh/)
    await screenshot('/tmp/corebrisk-quote-mobile.png')
    await send('Input.dispatchKeyEvent', { type: 'keyDown', key: 'Escape', code: 'Escape', windowsVirtualKeyCode: 27 })
    await send('Input.dispatchKeyEvent', { type: 'keyUp', key: 'Escape', code: 'Escape', windowsVirtualKeyCode: 27 })
    await poll(() => evaluate(`!document.querySelector('#quote-dialog').open`))
    for (const [plan, label] of [
      ['apps-script', 'Google Apps Script · từ 2,9 triệu'],
      ['appsheet', 'AppSheet · từ 7,9 triệu'],
      ['sheets-extension', 'Tiện ích Google Sheets · từ 3,9 triệu'],
    ]) {
      await click(`#bang-gia-google [data-select-plan="${plan}"]`)
      assert.equal(await evaluate(`document.querySelector('#plan').value`), plan)
      assert.equal(await evaluate(`document.querySelector('#message').value`), 'Cần website doanh nghiệp với trang dịch vụ và blog.')
      await click('#quote-form button[type="submit"]')
      assert.equal(await evaluate(`document.querySelector('#quote-dialog').open`), true)
      assert.equal(await evaluate(`document.querySelector('#quote-summary').value.includes(${JSON.stringify(label)})`), true)
      await click('.dialog-close')
    }
    await click('.faq-list details:nth-child(2) summary')
    assert.equal(await evaluate(`document.querySelector('.faq-list details:nth-child(2)').open`), true)
    await send('Emulation.setScriptExecutionDisabled', { value: true })
    await send('Page.reload')
    await delay(500)
    await send('Emulation.setScriptExecutionDisabled', { value: false })
    assert.match(await evaluate(`document.querySelector('#bang-gia').textContent`), /14,9/)
    assert.equal(await evaluate(`document.querySelector('#quote-form button[type="submit"]').disabled`), true)

    // Follow the real showcase URL, then return from the demo with its concept selected.
    const demoUrl = await evaluate(`document.querySelector('.architecture-preview').href`)
    assert.equal(demoUrl, 'http://127.0.0.1:4187/demos/an-studio/')
    await send('Page.navigate', { url: demoUrl })
    await poll(() => evaluate(`document.readyState === 'complete' && document.querySelector('.filters') && !document.querySelector('.filters').hidden`))
    await evaluate('document.fonts.ready')
    assert.equal(await evaluate(`document.querySelectorAll('h1').length`), 1)
    assert.deepEqual(await evaluate(`[...document.querySelectorAll('a[href^="#"]')].map(a=>a.getAttribute('href')).filter(h=>h.length>1 && !document.getElementById(h.slice(1)))`), [])
    for (const width of [1440, 1024, 768, 600, 390, 320]) {
      await send('Emulation.setDeviceMetricsOverride', { width, height: 900, deviceScaleFactor: 1, mobile: width < 701 })
      assert.equal(await evaluate(`document.documentElement.scrollWidth <= ${width}`), true, `An Studio overflow at ${width}px`)
      assert.equal(await evaluate(`getComputedStyle(document.querySelector('.menu-toggle')).display !== 'none'`), width < 701)
    }
    await click('.menu-toggle')
    assert.equal(await evaluate(`document.querySelector('.menu-toggle').getAttribute('aria-expanded')`), 'true')
    await click('#navigation a[href="#du-an"]')
    assert.equal(await evaluate(`document.querySelector('.menu-toggle').getAttribute('aria-expanded')`), 'false')
    await click('[data-filter="home"]')
    assert.equal(await evaluate(`document.querySelectorAll('.project-card:not([hidden])').length`), 1)
    await evaluate(`document.querySelector('[data-project="garden-house"]').focus()`)
    await click('[data-project="garden-house"]')
    assert.equal(await evaluate(`document.querySelector('#project-dialog').open`), true)
    assert.equal(await evaluate(`document.querySelector('#dialog-title').textContent`), 'The Garden House')
    await send('Input.dispatchKeyEvent', { type: 'keyDown', key: 'Escape', code: 'Escape', windowsVirtualKeyCode: 27 })
    await send('Input.dispatchKeyEvent', { type: 'keyUp', key: 'Escape', code: 'Escape', windowsVirtualKeyCode: 27 })
    await poll(() => evaluate(`!document.querySelector('#project-dialog').open`))
    assert.equal(await evaluate(`document.activeElement.dataset.project`), 'garden-house')
    await click('[data-filter="interior"]')
    assert.equal(await evaluate(`document.querySelectorAll('.project-card:not([hidden])').length`), 2)
    await click('[data-filter="all"]')
    assert.equal(await evaluate(`document.querySelectorAll('.project-card:not([hidden])').length`), 3)
    await evaluate(`Promise.all([...document.images].map(img => { img.loading = 'eager'; return img.decode(); }))`)
    assert.equal(await evaluate(`[...document.images].every(img => img.complete && img.naturalWidth > 0)`), true)
    await send('Emulation.setDeviceMetricsOverride', { width: 1440, height: 1050, deviceScaleFactor: 1, mobile: false })
    await evaluate(`document.documentElement.style.scrollBehavior = 'auto'; window.scrollTo(0,0)`)
    await screenshot('/tmp/an-studio-desktop.png', true)
    await screenshot('/tmp/an-studio-desktop-hero.png')
    await send('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true })
    await screenshot('/tmp/an-studio-mobile.png', true)
    await screenshot('/tmp/an-studio-mobile-hero.png')
    await click('.contact-button')
    await poll(() => evaluate(`document.querySelector('#message')?.value.includes('An Studio')`))
    assert.equal(await evaluate(`location.hash`), '#lien-he')
    await send('Emulation.setScriptExecutionDisabled', { value: true })
    await send('Page.navigate', { url: demoUrl })
    await delay(500)
    await send('Emulation.setScriptExecutionDisabled', { value: false })
    await poll(() => evaluate(`document.readyState === 'complete' && document.querySelector('.project-stories')`))
    assert.equal(await evaluate(`document.querySelector('.project-stories').hidden`), false)
    assert.equal(await evaluate(`getComputedStyle(document.querySelector('#navigation')).display !== 'none'`), true)
    assert.equal(await evaluate(`document.querySelectorAll('.project-stories details').length`), 3)
    await send('Page.navigate', { url: 'http://127.0.0.1:4187/' })
    await poll(() => evaluate(`document.readyState === 'complete' && document.querySelector('.saas-preview')`))
    await testOrbitApp({ send, evaluate, screenshot })
    await testAster({ send, evaluate, screenshot, downloads })
    await testServices({ send, evaluate, screenshot })
    assert.deepEqual(errors, [])
    console.log('PASS: CoreBrisk and An Studio at 6 responsive widths, navigation, package/concept selection, quote validation, clipboard/TXT, demo filters, project dialog, local images, return to consultation, content without JavaScript. Screenshots: /tmp/corebrisk-*.png and /tmp/an-studio-*.png')
  })
} catch (error) {
  console.error(error, serverError)
  process.exitCode = 1
} finally {
  server.kill('SIGTERM')
  await rm(downloads, { recursive: true, force: true })
}
