import assert from 'node:assert/strict'
import { testAster } from './aster.mjs'
import { testServices } from './services.mjs'
import { testNavigation } from './navigation.mjs'
import { testCtas } from './ctas.mjs'
import { testPricing } from './pricing.mjs'
import { testOrbitApp } from './orbit-app.mjs'
import { spawn } from 'node:child_process'
import { mkdtemp, readdir, readFile, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { withBrowser, poll, delay } from './browser-helper.mjs'

